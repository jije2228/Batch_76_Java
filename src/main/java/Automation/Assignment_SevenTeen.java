package Automation;

public class Assignment_SevenTeen {
/*
WAP on continue keyword
*/


    static void main(String[] args) {

        for (int i = 0; i <= 20; i ++){
            if (i == 5)
            {
                continue;
            } else if (i == 11) {
                continue;
            }

            System.out.println(i);
        }

    }


}
